#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.md from the dependency graph in Cargo.lock.

The licence expression of each crate is the one its manifest declares. The script does not read licence texts and does
not decide compatibility: a person reviews the list at each release.

Run from the repository root:  python3 scripts/third_party_licenses.py
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_LICENSES.md"


def main() -> int:
    raw = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    meta = json.loads(raw)
    members = set(meta["workspace_members"])
    rows = sorted(
        (p["name"], p["version"], p.get("license") or "not declared", p.get("repository") or "")
        for p in meta["packages"]
        if p["id"] not in members
    )
    lines = [
        "# Third-party licences",
        "",
        "Generated by `scripts/third_party_licenses.py` from `Cargo.lock`. The expressions are the ones each crate",
        "declares in its manifest. A person reviews them at each release; this file does not state that they are",
        "compatible with the project licence until that review is recorded.",
        "",
        f"Crates: {len(rows)}.",
        "",
        "| Crate | Version | Licence expression | Source |",
        "|---|---|---|---|",
    ]
    for name, version, lic, repo in rows:
        lines.append(f"| {name} | {version} | {lic} | {repo or 'crates.io'} |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(rows)} crates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
